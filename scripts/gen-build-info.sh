#!/usr/bin/env bash
# Generates build provenance (semver + commit SHA) for the Go server and the C
# server to embed. The version is derived from the GIT_TAG environment variable
# (a vX.Y.Z git tag -- the same convention scripts/bump-version.sh enforces):
#   - GIT_TAG empty (dev build) -> 0.0.0
#   - GIT_TAG=v1.2.3            -> 1.2.3 (strip the v)
#   - GIT_TAG=anything else     -> fail loudly (exit 1)
# The commit is GIT_COMMIT (git rev-parse HEAD) used verbatim; empty -> unknown.
#
# Runs as a Bazel genrule, so the output path arrives as an argument (cwd is
# the execroot runfiles tree, never assumed). Both env vars reach the action
# via --action_env (see the Makefile).
#
# Usage: gen-build-info.sh <go|c> <output>
set -euo pipefail

OUT_LANG="${1:?usage: gen-build-info.sh <go|c> <output>}"
OUTPUT="${2:?usage: gen-build-info.sh <go|c> <output>}"

GIT_TAG="${GIT_TAG:-}"
GIT_COMMIT="${GIT_COMMIT:-}"

# Guard clauses: resolve the version and commit up front, before writing.
if [[ -z "${GIT_TAG}" ]]; then
    VERSION="0.0.0"
elif [[ "${GIT_TAG}" =~ ^v([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
    VERSION="${BASH_REMATCH[1]}.${BASH_REMATCH[2]}.${BASH_REMATCH[3]}"
else
    echo "ERROR: GIT_TAG='${GIT_TAG}' is not a valid vX.Y.Z git tag." >&2
    echo "Expected exactly ^v[0-9]+\\.[0-9]+\\.[0-9]+$ (e.g. v1.2.3)." >&2
    echo "Leave GIT_TAG unset/empty for the dev default 0.0.0." >&2
    exit 1
fi

if [[ -z "${GIT_COMMIT}" ]]; then
    COMMIT="unknown"
else
    COMMIT="${GIT_COMMIT}"
fi

# VERSION is regex-validated above and COMMIT is a git SHA, so neither can
# contain a quote (or shell metacharacter) -- direct substitution is safe.
case "${OUT_LANG}" in
go)
    cat > "${OUTPUT}" <<EOF
// Code generated by gen-build-info.sh. DO NOT EDIT.

package main

// Version is the release semver derived from the vX.Y.Z git tag (0.0.0 when
// the build is untagged).
const Version = "${VERSION}"

// Commit is the full git commit SHA the binary was built from (unknown when
// unset).
const Commit = "${COMMIT}"
EOF
    ;;
c)
    cat > "${OUTPUT}" <<EOF
/* Code generated by gen-build-info.sh. DO NOT EDIT. */
#ifndef STRIMSERVER_BUILD_INFO_H
#define STRIMSERVER_BUILD_INFO_H

/* Release semver derived from the vX.Y.Z git tag (0.0.0 when untagged). */
#define STRIMSERVER_VERSION "${VERSION}"

/* Full git commit SHA the binary was built from (unknown when unset). */
#define STRIMSERVER_COMMIT "${COMMIT}"

#endif
EOF
    ;;
*)
    echo "ERROR: unknown language '${OUT_LANG}' (expected 'go' or 'c')." >&2
    exit 1
    ;;
esac
